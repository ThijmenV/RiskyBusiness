const test=require('node:test');const assert=require('node:assert/strict');
const fs=require('node:fs');const os=require('node:os');const path=require('node:path');
const {Pool}=require('pg');const request=require('supertest');
const {createStorage}=require('../src/storage');const {createApp}=require('../src/app');
const {mergeSources}=require('../scripts/migrate-legacy');const {importPostgres}=require('../scripts/import-postgres');const {backup}=require('../scripts/backup');
test('PostgreSQL: verified import, concurrent writes, transactional group creation, durable sessions and backup restore',{skip:!process.env.TEST_DATABASE_URL},async t=>{
  const admin=new Pool({connectionString:process.env.TEST_DATABASE_URL});
  const schemas=[`risky_test_${process.pid}`,`risky_restore_${process.pid}`];
  const scoped=schema=>{const u=new URL(process.env.TEST_DATABASE_URL);u.searchParams.set('options','-c search_path='+schema);return u.toString();};
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'risky-pg-'));
  const pools=[];const sessions=[];
  t.after(async()=>{for(const s of sessions)s.close();for(const p of pools)await p.close();for(const s of schemas)await admin.query(`DROP SCHEMA IF EXISTS ${s} CASCADE`);await admin.end();fs.rmSync(dir,{recursive:true,force:true});});
  for(const s of schemas) await admin.query(`CREATE SCHEMA ${s}`);
  const unmigrated=createStorage({databaseUrl:scoped(schemas[1]),schemaMode:'verify'});pools.push(unmigrated);
  await assert.rejects(unmigrated.ensureReady(),/requires migration/);
  const file=path.join(dir,'import.json');
  const fixture=require('../fixtures/legacy-sources.cjs').createLegacySources(path.join(dir,'sources'));
  const data=mergeSources(fixture.files);
  fs.writeFileSync(file,JSON.stringify(data));
  assert.deepEqual(await importPostgres(file,scoped(schemas[0])),{users:2,groups:2,group_members:2,game_state:2,game_history:0});
  await assert.rejects(importPostgres(file,scoped(schemas[0])),/not empty/);
  const storage=createStorage({databaseUrl:scoped(schemas[0])});pools.push(storage);await storage.ensureReady();
  const gid=data.groups[0].id;
  const readonly=createStorage({databaseUrl:scoped(schemas[0]),schemaMode:'verify'});pools.push(readonly);await readonly.ensureReady();
  assert.equal((await readonly.checkHealth()).ok,true);
  const snap=await storage.getGameSnapshot(gid);assert.deepEqual(snap.game,JSON.parse(data.game_state[0].payload));
  const race=await Promise.allSettled([storage.saveGameState(gid,snap.game,0),storage.saveGameState(gid,{troops:{}},0)]);
  assert.equal(race.filter(r=>r.status==='fulfilled').length,1);
  assert.equal(race.find(r=>r.status==='rejected').reason.status,409);
  assert.equal((await storage.getGameHistory(gid)).length,1);
  assert.deepEqual((await storage.getHistoricalGame(gid,0)).game,snap.game);
  await storage.pool.query("CREATE FUNCTION reject_game() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'deliberate test failure'; END $$");
  await storage.pool.query('CREATE TRIGGER reject_game BEFORE INSERT ON game_state FOR EACH ROW EXECUTE FUNCTION reject_game()');
  await assert.rejects(storage.createGroup('Must roll back',data.users[0].id));
  assert.equal(Number((await storage.pool.query("SELECT count(*) FROM groups WHERE name='Must roll back'")).rows[0].count),0);
  await storage.pool.query('DROP TRIGGER reject_game ON game_state');
  const app1=createApp({storage});sessions.push(app1.locals.sessionStore);
  const signup=await request(app1).post('/api/auth/signup').send({username:'Durable',email:'durable@example.invalid',password:'durable-test123'});assert.equal(signup.status,201);
  const app2=createApp({storage});sessions.push(app2.locals.sessionStore);
  const me=await request(app2).get('/api/auth/me').set('Cookie',signup.headers['set-cookie']);assert.equal(me.status,200);assert.equal(me.body.user.username,'Durable');
  const backupFile=path.join(dir,'backup.json');await backup(backupFile,{databaseUrl:scoped(schemas[0])});
  assert.equal(fs.statSync(backupFile).mode & 0o777,0o600);
  await importPostgres(backupFile,scoped(schemas[1]));
  const restored=createStorage({databaseUrl:scoped(schemas[1])});pools.push(restored);
  assert.deepEqual(await restored.getGameSnapshot(gid),await storage.getGameSnapshot(gid));
  assert.deepEqual(await restored.getGameHistory(gid),await storage.getGameHistory(gid));
  assert.equal((await restored.getUserByEmail('durable@example.invalid')).username,'Durable');
});
