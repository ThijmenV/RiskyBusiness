const {test,expect}=require('@playwright/test');
test('desktop and mobile game, log edits, persistence, safe rendering and conflict recovery',async({page,context})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',d=>d.accept());
  await page.goto('/');
  await page.locator('#signup-form [name=username]').fill('<img src=x onerror=alert(1)>');
  await page.locator('#signup-form [name=email]').fill(`browser-${Date.now()}@example.invalid`);
  await page.locator('#signup-form [name=password]').fill('browser-secret123');
  await page.locator('#signup-form button').click();
  await expect(page.locator('#app-view')).toBeVisible();
  await page.locator('#group-create-form [name=name]').fill('Browser group');
  await page.locator('#group-create-form button').click();
  await page.getByRole('link',{name:'Open game'}).click();
  await expect(page.locator('#world-map path').first()).toBeAttached();
  await expect(page.locator('body')).not.toHaveClass(/loading/);
  await expect(page.locator('#players-list img')).toHaveCount(0);
  const country=page.locator('#world-map path[data-id="528"]');
  await country.dispatchEvent('click');
  await page.locator('#troop-entries button').filter({hasText:/^\+$/}).first().click();
  await expect(page.locator('#troop-entries .troop-count').first()).toHaveText('1');
  await expect(page.locator('#save-status')).toHaveText('Saved ✓');
  await page.getByRole('button',{name:'📊 STATS'}).click();
  await page.locator('#entry-name').fill('<img src=x onerror=alert(2)>');
  await page.locator('#entry-country').selectOption('528');
  await page.locator('#entry-submit-btn').click();
  await expect(page.locator('#log-list .timeline-entry')).toHaveCount(1);
  await expect(page.locator('#log-list img')).toHaveCount(0);
  await expect(page.locator('#save-status')).toHaveText('Saved ✓');
  await page.locator('#log-list button').filter({hasText:'✎'}).click();
  await page.locator('#entry-country').selectOption('56');
  await page.locator('#entry-submit-btn').click();
  await expect(page.locator('#save-status')).toHaveText('Saved ✓');
  const state=await page.evaluate(async()=>{const r=await fetch(`/api/groups/${location.pathname.split('/')[2]}/game`);return r.json();});
  expect(state.game.troops['528']['1']).toBe(1);
  expect(state.game.troops['56']['1']).toBe(1);
  await page.locator('#log-list button').filter({hasText:'✕'}).click();
  await expect(page.locator('#log-list .timeline-entry')).toHaveCount(0);
  await expect(page.locator('#save-status')).toHaveText('Saved ✓');
  await page.getByRole('button',{name:'✕ CLOSE'}).click();
  await page.reload();
  await expect(page.locator('body')).not.toHaveClass(/loading/);
  await country.dispatchEvent('click');
  await expect(page.locator('#troop-entries .troop-count').first()).toHaveText('1');
  const second=await context.newPage();await second.goto(page.url());
  await expect(second.locator('body')).not.toHaveClass(/loading/);
  await page.locator('#troop-entries button').filter({hasText:/^\+$/}).first().click();
  await expect(page.locator('#save-status')).toHaveText('Saved ✓');
  await second.locator('#world-map path[data-id="528"]').dispatchEvent('click');
  await second.locator('#troop-entries button').filter({hasText:/^\+$/}).first().click();
  await expect(second.locator('#sync-error')).toBeVisible();
  await expect(second.locator('#sync-message')).toContainText('another session');
  await second.close();
  await page.setViewportSize({width:390,height:844});
  await country.dispatchEvent('click');
  await page.locator('#mobile-open-btn').click();
  await page.locator('#m-troop-entries .tb-toggle').click();
  await expect(page.locator('#save-status')).toHaveText('Saved ✓');
  // The recovered roster must render six independent players, not just login accounts.
  const {players}=require('../scripts/recover-jsonbin').historicalSettings();
  const url=new URL(page.url()).pathname.split('/')[2];
  const before=await (await page.request.get(`/api/groups/${url}/game`)).json();
  const setRoster=await page.request.post(`/api/groups/${url}/game`,{headers:{'If-Match':String(before.version)},data:{...before.game,players}});
  expect(setRoster.status()).toBe(200);
  await page.setViewportSize({width:1280,height:900});
  await page.reload();await expect(page.locator('body')).not.toHaveClass(/loading/);
  await expect(page.locator('#players-list .player-card')).toHaveCount(6);
  await expect(page.locator('#players-list')).toContainText('Thijmen');
  await page.locator('#players-list input[type=color]').nth(1).evaluate(el=>{el.value='#112233';el.dispatchEvent(new Event('change'));});
  await expect(page.locator('#save-status')).toHaveText('Saved ✓');
  await page.screenshot({path:'test-results/desktop-game.png'});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'test-results/mobile-game.png'});
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'RESET',exact:true}).click();
  const saved=await download;await saved.saveAs('test-results/before-reset.json');
  await expect(page.locator('#save-status')).toHaveText('Saved ✓');
  const cleared=await (await page.request.get(`/api/groups/${url}/game`)).json();
  expect(cleared.game.troops).toEqual({});expect(cleared.game.kissLog).toEqual([]);expect(cleared.game.players).toHaveLength(6);
  await page.locator('input[type=file]').setInputFiles('test-results/before-reset.json');
  await expect(page.locator('#save-status')).toHaveText('Backup restored ✓');
  const restored=await (await page.request.get(`/api/groups/${url}/game`)).json();
  expect(restored.game.troops['528']['1']).toBe(2);
  await page.getByRole('button',{name:'HISTORY',exact:true}).click();
  await expect(page.locator('#history-list button').first()).toBeVisible();
  const historyDownload=page.waitForEvent('download');
  await page.locator('#history-list button').first().click();await historyDownload;
  await expect(page.locator('#save-status')).toHaveText('Version restored ✓');
  expect((await (await page.request.get(`/api/groups/${url}/game`)).json()).game.troops).toEqual({});
  expect(errors).toEqual([]);
});
